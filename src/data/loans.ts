// Datos de referencia de líneas de préstamos de bancos argentinos.
// Actualizado: septiembre 2026. Fuentes citadas en `fuente`: se prioriza el sitio
// oficial de cada banco cuando publica sus tasas vigentes; si no se encontró un
// dato oficial claro, se cita prensa especializada o se deja como estimación
// orientativa (marcado `verificado: false`).
// SIEMPRE verificar la tasa vigente en el sitio oficial de cada banco antes de decidir,
// ya que además de cambiar seguido, muchos bancos ofrecen tasas distintas según seas
// empleado en relación de dependencia (mejor tasa, generalmente con cuenta sueldo) o
// monotributista/autónomo (tasa más alta o línea específica, con más documentación).

export type TipoPrestamo = 'personal' | 'prendario' | 'hipotecario' | 'jubilados'

export type CondicionLaboral = 'empleado' | 'monotributista'

export interface LoanOffer {
  id: string
  banco: string
  tipo: TipoPrestamo
  /** Tasa Nominal Anual, en % */
  tna: number
  /** Costo Financiero Total anual, en % (incluye seguros, gastos e IVA) */
  cft: number
  montoMin: number
  montoMax: number
  plazoMinMeses: number
  plazoMaxMeses: number
  requisitos: string
  sitioWeb: string
  /** true si la tasa fue confirmada por una fuente periodística/oficial reciente */
  verificado: boolean
  fuente?: string
  nota?: string
  /**
   * Condiciones laborales que realmente pueden acceder a ESTA tasa/oferta puntual.
   * Si se omite, se asume que aplica a cualquier condición laboral (línea general).
   */
  segmentos?: CondicionLaboral[]
}

